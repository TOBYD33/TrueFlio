// reminder-service.ts
// Manages reminders: create, list upcoming, fire due ones, reschedule recurring.
// Reminders support an optional due_time (WAT). fireDueReminders runs every
// minute and fires anything whose date+time has passed, including overdue
// reminders missed while the server was down.

import { supabase } from './supabase'
import { sendWhatsAppMessage } from './twilio-sender'
import { notifyOwner } from './notification-service'
import { notifyOrgMembers } from './notifications'

// Reminders with no explicit time fire at this time of day (WAT)
const DEFAULT_FIRE_TIME = '08:00'

// Africa/Lagos is UTC+1 year-round (no DST)
function lagosNow(): Date {
  return new Date(Date.now() + 60 * 60 * 1000)
}

function lagosDateStr(d: Date): string {
  return d.toISOString().split('T')[0]
}

function lagosTimeStr(d: Date): string {
  return d.toISOString().split('T')[1].slice(0, 5) // HH:MM
}

// Thrown when a one-off reminder resolves to a date/time already in the
// past at the moment it's being created — defense-in-depth against the bug
// where a bad date from upstream parsing got silently inserted and then
// fired instantly with a false "sorry for the delay" apology. Recurring
// reminders are exempt: their first occurrence legitimately CAN look "past"
// relative to today (e.g. "every 5th of the month" set on the 20th), and
// the scheduler already advances those correctly.
export class PastDueReminderError extends Error {}

export async function setReminder(params: {
  orgId: string
  title: string
  dueDate: string
  recurrence: string
  category?: string
  dueTime?: string // 'HH:MM' 24h WAT
  clientId?: string // links a follow-up reminder to a lead/client record
}) {
  if (params.recurrence === 'once') {
    const nowD = lagosNow()
    const today = lagosDateStr(nowD)
    const nowTime = lagosTimeStr(nowD)
    const isPastDate = params.dueDate < today
    const isPastTimeToday = params.dueDate === today && !!params.dueTime && params.dueTime < nowTime
    if (isPastDate || isPastTimeToday) {
      throw new PastDueReminderError(
        `Resolved date/time (${params.dueDate}${params.dueTime ? ' ' + params.dueTime : ''}) is already in the past.`
      )
    }
  }

  // Upsert-by-intent: if an active reminder with the same title and date
  // already exists, update it instead of creating a duplicate. The AI can
  // emit SET_REMINDER repeatedly for one conversation ("set it" / "did you
  // set it?" / "change it to 11:40") — that must never mean three rows.
  const { data: existing } = await supabase
    .from('reminders')
    .select('id')
    .eq('org_id', params.orgId)
    .eq('due_date', params.dueDate)
    .eq('status', 'active')
    .ilike('title', params.title)
    .maybeSingle()

  if (existing) {
    const { data: updated, error: updErr } = await supabase
      .from('reminders')
      .update({
        due_time: params.dueTime || null,
        recurrence: params.recurrence,
        category: params.category || 'custom',
        ...(params.clientId ? { client_id: params.clientId } : {}),
      })
      .eq('id', existing.id)
      .select()
      .single()
    if (updErr) throw new Error(updErr.message)
    return updated
  }

  const { data, error } = await supabase
    .from('reminders')
    .insert({
      org_id: params.orgId,
      title: params.title,
      due_date: params.dueDate,
      due_time: params.dueTime || null,
      recurrence: params.recurrence,
      category: params.category || 'custom',
      // Only include client_id when one was actually passed — never send a
      // key for a column that might not exist on every deployment. An
      // unconditional client_id here previously made EVERY reminder insert
      // fail (PGRST204: column not found) the moment that column was
      // referenced before its migration had been run, and the failure was
      // invisible because the bot's confirmation text is generated by the
      // AI independently of whether this write actually succeeds.
      ...(params.clientId ? { client_id: params.clientId } : {}),
    })
    .select()
    .single()

  if (error) throw new Error(error.message)
  return data
}

export async function getUpcomingReminders(orgId: string, daysAhead: number) {
  const today = new Date().toISOString().split('T')[0]
  const future = new Date()
  future.setDate(future.getDate() + daysAhead)
  const futureStr = future.toISOString().split('T')[0]

  const { data, error } = await supabase
    .from('reminders')
    .select('*')
    .eq('org_id', orgId)
    .eq('status', 'active')
    .is('archived_at', null)
    .gte('due_date', today)
    .lte('due_date', futureStr)
    .order('due_date', { ascending: true })

  if (error) throw new Error(error.message)
  return data || []
}

// ── Archive / Restore / Stop-recurring / Permanent delete / Edit ─────────
// Shared by the web Reminders page and Tello/WhatsApp (action-executor.ts),
// so both surfaces stay behaviourally identical — see the notification-bell
// build's precedent (notifications.ts) for the same "one function, two
// callers" shape.

async function findActiveReminderByTitle(orgId: string, title: string) {
  const { data } = await supabase
    .from('reminders')
    .select('*')
    .eq('org_id', orgId)
    .ilike('title', `%${title}%`)
    .is('archived_at', null)
    .in('status', ['active', 'fired'])
    .order('due_date', { ascending: true })
    .limit(1)
    .maybeSingle()
  return data
}

async function findArchivedReminderByTitle(orgId: string, title: string) {
  const { data } = await supabase
    .from('reminders')
    .select('*')
    .eq('org_id', orgId)
    .ilike('title', `%${title}%`)
    .not('archived_at', 'is', null)
    .order('archived_at', { ascending: false })
    .limit(1)
    .maybeSingle()
  return data
}

export class ReminderNotFoundError extends Error {}

// Archives ONE occurrence — for a recurring reminder this only hides it
// until it next fires and rolls its due_date forward (see fireDueReminders
// below, which clears archived_at at that point), it does NOT end the
// series. Use stopRecurringReminder for that.
export async function archiveReminderByTitle(orgId: string, title: string) {
  const reminder = await findActiveReminderByTitle(orgId, title)
  if (!reminder) throw new ReminderNotFoundError(`No active reminder matching "${title}"`)
  const { error } = await supabase.from('reminders').update({ archived_at: new Date().toISOString() }).eq('id', reminder.id)
  if (error) throw new Error(error.message)
  return reminder
}

export async function restoreReminderByTitle(orgId: string, title: string) {
  const reminder = await findArchivedReminderByTitle(orgId, title)
  if (!reminder) throw new ReminderNotFoundError(`No archived reminder matching "${title}"`)
  const { error } = await supabase.from('reminders').update({ archived_at: null }).eq('id', reminder.id)
  if (error) throw new Error(error.message)
  return reminder
}

// Ends a recurring series without deleting its history — sets recurrence
// to 'once' so fireDueReminders' existing advance-or-terminate logic lets
// it fire (if not archived) exactly one more time and then naturally
// terminates via status = 'fired', instead of rolling forward forever.
export async function stopRecurringReminderByTitle(orgId: string, title: string) {
  const reminder = await findActiveReminderByTitle(orgId, title)
  if (!reminder) throw new ReminderNotFoundError(`No active reminder matching "${title}"`)
  if (reminder.recurrence === 'once') return reminder // nothing to stop
  const { error } = await supabase.from('reminders').update({ recurrence: 'once' }).eq('id', reminder.id)
  if (error) throw new Error(error.message)
  return reminder
}

// Searches BOTH active and archived reminders — permanently deleting is a
// valid action from either state (e.g. "delete my old gym reminder" for
// something never explicitly archived first).
export async function deleteReminderPermanentlyByTitle(orgId: string, title: string) {
  const { data: reminder } = await supabase
    .from('reminders')
    .select('*')
    .eq('org_id', orgId)
    .ilike('title', `%${title}%`)
    .order('due_date', { ascending: true })
    .limit(1)
    .maybeSingle()
  if (!reminder) throw new ReminderNotFoundError(`No reminder matching "${title}"`)
  const { error } = await supabase.from('reminders').delete().eq('id', reminder.id)
  if (error) throw new Error(error.message)
  return reminder
}

export async function editReminderByTitle(orgId: string, title: string, updates: {
  newTitle?: string
  dueDate?: string
  dueTime?: string | null
  recurrence?: string
}) {
  const reminder = await findActiveReminderByTitle(orgId, title)
  if (!reminder) throw new ReminderNotFoundError(`No active reminder matching "${title}"`)
  const patch: Record<string, unknown> = {}
  if (updates.newTitle) patch.title = updates.newTitle
  if (updates.dueDate) patch.due_date = updates.dueDate
  if (updates.dueTime !== undefined) patch.due_time = updates.dueTime
  if (updates.recurrence) patch.recurrence = updates.recurrence
  const { data, error } = await supabase.from('reminders').update(patch).eq('id', reminder.id).select().single()
  if (error) throw new Error(error.message)
  return data
}

// Called by scheduler every minute. Fires anything due now or overdue.
export async function fireDueReminders() {
  const now = lagosNow()
  const today = lagosDateStr(now)
  const nowTime = lagosTimeStr(now)

  const { data: reminders, error } = await supabase
    .from('reminders')
    .select(`*, organizations(id, name, currency, org_members(whatsapp_number, role, profiles(full_name, email)))`)
    .lte('due_date', today)
    .eq('status', 'active')

  if (error) { console.error('fireDueReminders query failed:', error); return }

  for (const reminder of reminders || []) {
    // Today's reminders wait until their time (or the default) has passed.
    // Past-date reminders are overdue — fire immediately.
    if (reminder.due_date === today) {
      const fireAt = (reminder.due_time || DEFAULT_FIRE_TIME).slice(0, 5)
      if (fireAt > nowTime) continue
    }

    const owner = reminder.organizations?.org_members?.find((m: any) => m.role === 'owner')

    // The user explicitly dismissed this occurrence — still advance (or
    // terminate) it below, same as normal, but skip notifying about it.
    if (reminder.archived_at) {
      const nextDate = getNextDate(reminder.due_date, reminder.recurrence)
      if (nextDate !== reminder.due_date) {
        await supabase.from('reminders').update({ due_date: nextDate, archived_at: null }).eq('id', reminder.id)
      } else {
        await supabase.from('reminders').update({ status: 'fired', fired_at: new Date().toISOString() }).eq('id', reminder.id)
      }
      continue
    }

    if (!owner?.whatsapp_number) continue

    // Use the CURRENT profile name at send time — names are user-editable
    const name = (owner as any)?.profiles?.full_name
    const greeting = name ? `Hi ${name.split(' ')[0]}! ` : ''

    const overdue = reminder.due_date < today
    const message = overdue
      ? `🔔 ${greeting}*Reminder: ${reminder.title}*\n\nThis was due on ${reminder.due_date} — sorry for the delay in delivering it.`
      : `🔔 ${greeting}*Reminder: ${reminder.title}*\n\nThis is due now.`

    try {
      await notifyOwner({
        whatsappNumber: owner.whatsapp_number,
        ownerEmail: (owner as any)?.profiles?.email,
        message,
        emailSubject: overdue ? `Overdue: ${reminder.title}` : `Reminder: ${reminder.title}`,
      })
      await notifyOrgMembers({
        orgId: reminder.org_id,
        category: reminder.category === 'tax' ? 'billing' : 'reminder',
        title: overdue ? `Overdue: ${reminder.title}` : `Reminder: ${reminder.title}`,
        body: overdue
          ? `This was due on ${reminder.due_date} — sorry for the delay in delivering it.`
          : `This is due now.`,
        link: '/reminders',
      })
    } catch (err) {
      console.error(`fireDueReminders: send failed for reminder ${reminder.id}:`, err)
      continue // keep status active — retry next minute
    }

    // Advance recurring reminders; anything else (including malformed
    // recurrence values) is marked fired so it can never loop every minute.
    // archived_at is cleared on advance — archiving only ever hides the
    // occurrence that was due, not the series, so the next occurrence
    // should show up normally in the Active view again.
    const nextDate = getNextDate(reminder.due_date, reminder.recurrence)
    if (nextDate !== reminder.due_date) {
      await supabase.from('reminders').update({ due_date: nextDate, archived_at: null }).eq('id', reminder.id)
    } else {
      await supabase.from('reminders').update({ status: 'fired', fired_at: new Date().toISOString() }).eq('id', reminder.id)
    }
  }
}

// Called by scheduler once daily — 3-day advance warnings
export async function fireAdvanceReminders() {
  const target = new Date()
  target.setDate(target.getDate() + 3)
  const targetStr = target.toISOString().split('T')[0]

  const { data: reminders } = await supabase
    .from('reminders')
    .select(`*, organizations(org_members(whatsapp_number, role, profiles(email)))`)
    .eq('due_date', targetStr)
    .eq('status', 'active')
    .is('archived_at', null)

  for (const reminder of reminders || []) {
    const owner = reminder.organizations?.org_members?.find((m: any) => m.role === 'owner')
    if (!owner?.whatsapp_number) continue

    const message = `⏰ *Upcoming in 3 days: ${reminder.title}*\n\nDue on ${reminder.due_date}. Want me to help you prepare?`
    await notifyOwner({
      whatsappNumber: owner.whatsapp_number,
      ownerEmail: (owner as any)?.profiles?.email,
      message,
      emailSubject: `Upcoming in 3 days: ${reminder.title}`,
    })
    await notifyOrgMembers({
      orgId: reminder.org_id,
      category: reminder.category === 'tax' ? 'billing' : 'reminder',
      title: `Upcoming in 3 days: ${reminder.title}`,
      body: `Due on ${reminder.due_date}.`,
      link: '/reminders',
    })
  }
}

function getNextDate(current: string, recurrence: string): string {
  const date = new Date(current)
  switch (recurrence) {
    case 'daily':   date.setDate(date.getDate() + 1); break
    case 'weekly':  date.setDate(date.getDate() + 7); break
    case 'monthly': date.setMonth(date.getMonth() + 1); break
    case 'yearly':  date.setFullYear(date.getFullYear() + 1); break
  }
  return date.toISOString().split('T')[0]
}
